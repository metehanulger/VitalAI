-- Ön Triaj veritabanı şeması (IBM DB2)
--
-- Her triaj başvurusu 4 kart tablosuna birer satır yazar. Dört kart kaydedildiğinde
-- her tablonun kodu (ID) HASTANE_LOG tablosunda tutulur; HASTANE_LOG kenarda duran
-- ve 4 kartı birbirine bağlayan kayıt tablosudur.
--
-- VARCHAR uzunlukları bayt cinsindendir. UTF-8'de bir karakter 4 bayta kadar
-- çıkabildiği için API'deki karakter limitinin 4 katı ayrılmıştır.
--
-- Çalıştırma: db2 connect to TRIAJDB && db2 -tvf init.sql

-- Kart 1: Temel Demografi
CREATE TABLE HASTA_DEMOGRAFI (
    ID           INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ISIM         VARCHAR(400) NOT NULL,
    YAS          SMALLINT NOT NULL,
    BOY          SMALLINT,
    KILO         DECIMAL(5, 1),
    KAN_GRUBU    VARCHAR(10) NOT NULL DEFAULT 'BILINMIYOR',
    KIMLIK_TURU  VARCHAR(10) NOT NULL,
    KIMLIK_NO    VARCHAR(20) NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT CK_DEMOGRAFI_YAS CHECK (YAS BETWEEN 0 AND 130),
    CONSTRAINT CK_DEMOGRAFI_BOY CHECK (BOY IS NULL OR BOY BETWEEN 20 AND 260),
    CONSTRAINT CK_DEMOGRAFI_KILO CHECK (KILO IS NULL OR KILO BETWEEN 0.5 AND 400),
    CONSTRAINT CK_DEMOGRAFI_KAN CHECK (KAN_GRUBU IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', '0+', '0-', 'BILINMIYOR')),
    CONSTRAINT CK_DEMOGRAFI_KIMLIK CHECK (KIMLIK_TURU IN ('TC', 'PASAPORT'))
);

CREATE INDEX IX_DEMOGRAFI_KIMLIK ON HASTA_DEMOGRAFI (KIMLIK_NO);

-- Kart 2: Tıbbi Geçmiş
CREATE TABLE TIBBI_GECMIS (
    ID                  INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    KRONIK_RAHATSIZLIK  VARCHAR(1600),
    SUREKLI_ILAC        VARCHAR(1600),
    PRIMARY KEY (ID)
);

-- Kart 3: Anlık Vitaller
CREATE TABLE ANLIK_VITALLER (
    ID                  INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NABIZ               SMALLINT NOT NULL,
    TANSIYON_SISTOLIK   SMALLINT NOT NULL,
    TANSIYON_DIASTOLIK  SMALLINT NOT NULL,
    SOLUNUM             SMALLINT NOT NULL,
    ATES                DECIMAL(4, 1) NOT NULL,
    SPO2                SMALLINT NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT CK_VITAL_NABIZ CHECK (NABIZ BETWEEN 20 AND 300),
    CONSTRAINT CK_VITAL_TANSIYON CHECK (TANSIYON_SISTOLIK > TANSIYON_DIASTOLIK),
    CONSTRAINT CK_VITAL_SOLUNUM CHECK (SOLUNUM BETWEEN 4 AND 80),
    CONSTRAINT CK_VITAL_ATES CHECK (ATES BETWEEN 25 AND 45),
    CONSTRAINT CK_VITAL_SPO2 CHECK (SPO2 BETWEEN 30 AND 100)
);

-- Kart 4: Şikayet
CREATE TABLE SIKAYET (
    ID            INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ANA_SIKAYET   VARCHAR(3200) NOT NULL,
    AGRI_SKALASI  SMALLINT NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT CK_SIKAYET_AGRI CHECK (AGRI_SKALASI BETWEEN 1 AND 10)
);

-- Hastane log verisi: 4 kartın kodları + hasta durumu + tarih, saat, sıra no
CREATE TABLE HASTANE_LOG (
    ID               INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    DEMOGRAFI_ID     INTEGER NOT NULL,
    TIBBI_GECMIS_ID  INTEGER NOT NULL,
    VITALLER_ID      INTEGER NOT NULL,
    SIKAYET_ID       INTEGER NOT NULL,
    HASTA_DURUMU     VARCHAR(10) NOT NULL,
    ACIKLAMA         VARCHAR(1000),
    KARAR_KAYNAGI    VARCHAR(20) NOT NULL,
    TARIH            DATE NOT NULL,
    SAAT             TIME NOT NULL,
    SIRA_NO          INTEGER NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT FK_LOG_DEMOGRAFI FOREIGN KEY (DEMOGRAFI_ID) REFERENCES HASTA_DEMOGRAFI (ID),
    CONSTRAINT FK_LOG_TIBBI_GECMIS FOREIGN KEY (TIBBI_GECMIS_ID) REFERENCES TIBBI_GECMIS (ID),
    CONSTRAINT FK_LOG_VITALLER FOREIGN KEY (VITALLER_ID) REFERENCES ANLIK_VITALLER (ID),
    CONSTRAINT FK_LOG_SIKAYET FOREIGN KEY (SIKAYET_ID) REFERENCES SIKAYET (ID),
    CONSTRAINT CK_LOG_DURUM CHECK (HASTA_DURUMU IN ('KIRMIZI', 'SARI', 'YESIL')),
    CONSTRAINT CK_LOG_KAYNAK CHECK (KARAR_KAYNAGI IN ('KURAL', 'WATSONX', 'KURAL+WATSONX', 'MANUEL')),
    -- Sıra numarası her gün 1'den başlar
    CONSTRAINT UQ_LOG_TARIH_SIRA UNIQUE (TARIH, SIRA_NO)
);
